/* -*- C++ -*- */
/**
 * @file EC_Multiple.h
 * @brief Declarations for the multiple Event Channel test.
 *
 * The test connects multiple event channels and their consumers,
 * suppliers, and proxies to exercise locality in event delivery.
 */

#ifndef EC_MULTIPLE_H
#define EC_MULTIPLE_H

#include <array>
#include <atomic>
#include "ace/SString.h"

#if !defined (ACE_LACKS_PRAGMA_ONCE)
# pragma once
#endif /* ACE_LACKS_PRAGMA_ONCE */

#include "ace/High_Res_Timer.h"
#include "ace/Condition_Thread_Mutex.h"
#include "orbsvcs/RtecEventChannelAdminC.h"
#include "orbsvcs/RtecEventCommS.h"
#include "orbsvcs/Channel_Clients_T.h"
#include "orbsvcs/Event/EC_Gateway_Sched.h"
#include "orbsvcs/CosNamingC.h"
#include "tao/PortableServer/Servant_var.h"

class Test_ECG;

/**
 * @brief Supplies events and handles event-channel timeout events.
 *
 * The test can configure one or more suppliers, use the event channel
 * or short-circuit it, and optionally use the gateway. This servant
 * connects as a timeout consumer and delegates each timeout to Test_ECG.
 */
class Test_Supplier : public POA_RtecEventComm::PushSupplier
{
public:
  Test_Supplier (Test_ECG* test, void* cookie);
  Test_Supplier (Test_Supplier const&) = delete;
  Test_Supplier (Test_Supplier&&) = delete;
  Test_Supplier& operator= (Test_Supplier const&) = delete;
  Test_Supplier& operator= (Test_Supplier&&) = delete;

  /** Connect this supplier to the event channel. */
  void open (char const* name,
             int event_a, int event_b,
             int message_count,
             RtecScheduler::Period_t const& rate,
             RtecEventChannelAdmin::EventChannel_ptr ec);

  /** Disconnect this supplier from the event channel. */
  void close ();

  /** Start generating events at the requested rate. */
  void activate (char const* name,
                 RtecScheduler::Period_t const& rate,
                 RtecEventChannelAdmin::EventChannel_ptr ec);

  /** Handle timeout events delivered through the consumer adapter. */
  void push (RtecEventComm::EventSet const& events);
  /** Handle disconnection from the event-channel consumer proxy. */
  void disconnect_push_consumer ();

  /** Handle disconnection from the event-channel supplier proxy. */
  void disconnect_push_supplier () override;

  /** Return the event source ID assigned to this supplier. */
  RtecEventComm::EventSourceID supplier_id () const;

private:
  /** Test coordinator; borrowed for the lifetime of this servant. */
  Test_ECG* test_;

  /** Stable slot address used to identify this supplier in callbacks. */
  void *cookie_;

  /** Event source ID assigned during connection. */
  RtecEventComm::EventSourceID supplier_id_;

  /** First event type generated by this supplier. */
  int event_a_;
  /** Second event type generated by this supplier. */
  int event_b_;

  /** Number of messages sent by this supplier. */
  int message_count_;

  /** Proxy used when sending events to the event channel. */
  RtecEventChannelAdmin::ProxyPushConsumer_var consumer_proxy_;

  /** Adapter used to receive event-channel timeout events. */
  ACE_PushConsumer_Adapter<Test_Supplier> consumer_;

  /** Proxy used to receive timeout events from the event channel. */
  RtecEventChannelAdmin::ProxyPushSupplier_var supplier_proxy_;
};

/**
 * @brief Identifies the consumer that receives each event.
 *
 * Each servant forwards events to Test_ECG with a cookie that identifies
 * its slot in the consumer list.
 */
class Test_Consumer : public POA_RtecEventComm::PushConsumer
{
public:
  Test_Consumer (Test_ECG* test, void *cookie);
  Test_Consumer (Test_Consumer const&) = delete;
  Test_Consumer (Test_Consumer&&) = delete;
  Test_Consumer& operator= (Test_Consumer const&) = delete;
  Test_Consumer& operator= (Test_Consumer&&) = delete;

  /** Connect this consumer to the event channel. */
  void open (char const* name,
             int event_a, int event_b,
             RtecEventChannelAdmin::EventChannel_ptr ec);

  /** Disconnect this consumer from the event channel. */
  void close ();

  /** Forward received events to the test coordinator. */
  void push (RtecEventComm::EventSet const& events) override;
  /** Handle disconnection from the event-channel proxy. */
  void disconnect_push_consumer () override;

private:
  /** Test coordinator; borrowed for the lifetime of this servant. */
  Test_ECG* test_;

  /** Stable slot address used to identify this consumer in callbacks. */
  void *cookie_;

  /** Proxy used to receive events from the event channel. */
  RtecEventChannelAdmin::ProxyPushSupplier_var supplier_proxy_;
};

/**
 * @brief Exercises gateway behavior across multiple event channels.
 *
 * The test configures local and remote channels, suppliers, consumers,
 * and subscriptions from command-line options. It covers remote event
 * delivery, filtering, and local short-circuit mode.
 */
class Test_ECG
{
public:
  Test_ECG ();
  Test_ECG (Test_ECG const&) = delete;
  Test_ECG (Test_ECG&&) = delete;
  Test_ECG& operator= (Test_ECG const&) = delete;
  Test_ECG& operator= (Test_ECG&&) = delete;

  enum {
    /** Maximum number of events stored per consumer. */
    MAX_EVENTS = 1024,

    /** Maximum number of consumers. */
    MAX_CONSUMERS = 1024,

    /** Maximum number of suppliers. */
    MAX_SUPPLIERS = 1024
  };

  /** Execute the test using the supplied command-line options. */
  int run (int argc, ACE_TCHAR* argv[]);

  /**
   * Forward supplier events and collect delivery statistics.
   *
   * The consumer proxy is unused when testing short-circuit delivery.
   */
  void push_supplier (void* supplier_cookie,
                      RtecEventChannelAdmin::ProxyPushConsumer_ptr consumer,
                      RtecEventComm::EventSet const& events);

  /** Collect statistics for events received by a consumer. */
  void push_consumer (void* consumer_cookie,
                      ACE_hrtime_t arrival,
                      RtecEventComm::EventSet const& events);

  /** Propagate shutdown after a supplier has completed its work. */
  void shutdown_supplier (void* supplier_cookie,
                          RtecEventComm::PushConsumer_ptr consumer);

private:
  /** Resolve an event channel by name. */
  RtecEventChannelAdmin::EventChannel_ptr
    get_ec (CosNaming::NamingContext_ptr naming_context,
            char const* ec_name);

  /** Connect and disconnect all configured suppliers. */
  void connect_suppliers (RtecEventChannelAdmin::EventChannel_ptr local_ec);
  void disconnect_suppliers ();

  /** Start event generation for all connected suppliers. */
  void activate_suppliers (RtecEventChannelAdmin::EventChannel_ptr local_ec);

  /** Connect the gateway and configure its subscription/publication lists. */
  void connect_ecg (RtecEventChannelAdmin::EventChannel_ptr local_ec,
                    RtecEventChannelAdmin::EventChannel_ptr remote_ec,
                    RtecScheduler::Scheduler_ptr remote_sch);

  /** Connect and disconnect all configured consumers. */
  void connect_consumers (RtecEventChannelAdmin::EventChannel_ptr local_ec);
  void disconnect_consumers ();

  /** Parse test-specific command-line options. */
  int parse_args (int argc, ACE_TCHAR* argv[]);

  /** Print aggregate and per-consumer results. */
  void dump_results ();

  /** Wait until event delivery is enabled. */
  void wait_until_ready ();

  struct Stats;
  /** Print results for one consumer. */
  void dump_results (ACE_TCHAR const* name, Stats& stats);

  /** Return nonzero when the event source belongs to a local supplier. */
  int local_source (RtecEventComm::EventSourceID id) const;

  /** Handle completion of one consumer. */
  void shutdown_consumer (int id);

private:
  /** Name of the local event channel. */
  ACE_CString lcl_name_;

  /** Name of the remote event channel. */
  ACE_CString rmt_name_;

  /** Gateway proxy that connects the two event channels. */
  TAO_EC_Gateway_Sched ecg_;

  /** Supported scheduling service modes. */
  enum {
    ss_global,
    ss_local,
    ss_runtime
  };

  /** Selected scheduling service mode. */
  int scheduling_type_;

  /** Number of disconnect/reconnect cycles for consumers and suppliers. */
  int consumer_disconnects_;
  int supplier_disconnects_;

  /** Whether events bypass the event channel for the overhead measurement. */
  bool short_circuit_;

  /** Servant owners; each cookie points to its stable slot in these arrays. */
  std::array<PortableServer::Servant_var<Test_Supplier>,
             Test_ECG::MAX_SUPPLIERS> suppliers_;
  std::array<PortableServer::Servant_var<Test_Consumer>,
             Test_ECG::MAX_CONSUMERS> consumers_;

  /** @todo Group the high- and low-priority configuration into named structs. */
  /** Number of high-priority suppliers. */
  int hp_suppliers_;
  /** Number of high-priority consumers. */
  int hp_consumers_;
  /** Prime-test iterations performed for each high-priority event. */
  int hp_workload_;
  /** Interval between high-priority events in microseconds. */
  int hp_interval_;
  /** Event count configured for high-priority suppliers. */
  int hp_message_count_;
  /** Event types generated and consumed by high-priority clients. */
  int hps_event_a_;
  int hps_event_b_;
  int hpc_event_a_;
  int hpc_event_b_;

  /** Number of low-priority suppliers. */
  int lp_suppliers_;
  /** Number of low-priority consumers. */
  int lp_consumers_;
  /** Prime-test iterations performed for each low-priority event. */
  int lp_workload_;
  /** Interval between low-priority events in microseconds. */
  int lp_interval_;
  /** Event count configured for low-priority suppliers. */
  int lp_message_count_;
  /** Event types generated and consumed by low-priority clients. */
  int lps_event_a_;
  int lps_event_b_;
  int lpc_event_a_;
  int lpc_event_b_;

  /** Optional schedule output path borrowed from the command line. */
  ACE_TCHAR const* schedule_file_;
  /** Optional process ID output path borrowed from the command line. */
  ACE_TCHAR const* pid_file_name_;

  /** Timing and latency results for one consumer. */
  struct Stats {
    /** Total time spent processing local events. */
    ACE_hrtime_t total_time_;
    /** Laxity values for local events. */
    std::array<float, MAX_EVENTS> laxity_;
    /** Local event latencies. */
    std::array<ACE_hrtime_t, MAX_EVENTS> lcl_latency_;
    /** Local event completion timestamps. */
    std::array<ACE_hrtime_t, MAX_EVENTS> end_;
    /** Number of local events recorded. */
    int lcl_count_;
    /** Remote event latencies. */
    std::array<ACE_hrtime_t, MAX_EVENTS> rmt_latency_;
    /** Number of remote events recorded. */
    int rmt_count_;
  };

  /** Results indexed by consumer slot. */
  Stats stats_[Test_ECG::MAX_CONSUMERS];

  /** Whether suppliers may proceed with event delivery. */
  bool ready_;
  TAO_SYNCH_MUTEX ready_mtx_;
  TAO_SYNCH_CONDITION ready_cnd_;

  /** Number of suppliers that have not completed. */
  std::atomic<int> running_suppliers_;
  /** Number of consumers that have not completed. */
  std::atomic<int> running_consumers_;

  /** Start and stop timestamps for the full test run. */
  ACE_hrtime_t test_start_;
  ACE_hrtime_t test_stop_;
};

#endif /* EC_MULTIPLE_H */
